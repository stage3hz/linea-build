// Self-contained HMAC-SHA256 (RFC 2104 over FIPS 180-4 SHA-256). React Native's
// expo-crypto only hashes UTF-8 strings, which would corrupt the raw key/pad
// bytes an HMAC needs, so the hash is implemented here over byte arrays. The
// result is verified against the RFC 4231 vectors in the test suite.
//
// This signs outgoing API requests with a per-build key so the server can turn
// away requests that aren't from a real INVIZENT build (see server/src/attest.js).
// The key is baked into the app and therefore extractable by a determined
// attacker; this raises the bar and gives a rotatable gate, it is not a secret
// channel. Authentication and end-to-end encryption do the real work.

